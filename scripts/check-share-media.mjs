import assert from 'node:assert/strict';
import { shareImageCandidates, createShareMediaLoader } from './share-media.mjs';
import { describeShareRecord, renderShareCard } from './share-cards.mjs';
import { createWebProfileHandler } from './web-profile-handler.mjs';
import { readFile } from 'node:fs/promises';
const records = JSON.parse(await readFile(new URL('../examples/share-records.json', import.meta.url), 'utf8'));
assert.equal(shareImageCandidates(records[0])[0], records[0].data.photo_url);
assert.equal(shareImageCandidates(records[1])[0], records[1].data.client_profiles.photos[0].url);
assert.equal(shareImageCandidates(records[2])[0], records[2].data.photos[0].url);
let fetched = [];
const chain = { rotate(){return this;},resize(){return this;},jpeg(){return this;},async toBuffer(){return Buffer.from('normalized-image');} };
const loader = createShareMediaLoader({ sharp: () => chain, allowedHosts:['images.example.com'], fetchImage: async (url, options) => { fetched.push(url.href); assert.equal(options.redirect,'error'); return new Response(Buffer.from('image'),{headers:{'content-type':'image/jpeg'}}); } });
const unsafe = { type:'coach', data:{photo_url:'https://127.0.0.1/private',photos:[{url:'http://images.example.com/a.jpg'},{url:'https://images.example.com/public.jpg'}]} };
const media = await loader(unsafe);
assert.deepEqual(fetched,['https://images.example.com/public.jpg']);
assert.ok(Buffer.isBuffer(media.image));
const d=describeShareRecord(records[0]);
const photo=renderShareCard(d,media),fallback=renderShareCard(d);
assert.ok(photo.svg.includes('data:image/jpeg;base64,'));
assert.ok(!photo.svg.includes('STRONGER, TOGETHER.'));
assert.notEqual(photo.imageUrl,fallback.imageUrl);
let calls=0;
const hidden=structuredClone(records[0]);hidden.data.profiles.open_to_offers=false;
const handler=createWebProfileHandler({loadRecord:async()=>hidden,loadMedia:async()=>{calls++;return media;},rasterize:async()=>Buffer.from('jpeg')});
assert.equal((await handler('/p/coach/rachel-green-1001/og.jpg')).status,404);
assert.equal(calls,0);
console.log('Passed media selection, safe host/protocol handling, JPEG normalization, photo card rendering/versioning, and no photo fetch for hidden coaches.');
